import { _electron as electron } from 'playwright';
import { resolve, join } from 'node:path';
import { mkdir, writeFile, readFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';

const output = resolve('.impeccable/review'); await mkdir(output, { recursive: true });
const profile = await mkdtemp(join(tmpdir(), 'aio-download-ui-'));
const packaged = process.argv[2]; const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ executablePath: resolve(packaged ?? 'node_modules/electron/dist/electron.exe'), args: packaged ? [`--user-data-dir=${profile}`] : [resolve('.'), `--user-data-dir=${profile}`], env, timeout: 60000 });
const report = { packaged: !!packaged, applicationSha256: '', checks: [], errors: [] };
try {
  const applicationPath = await app.evaluate(({ app }) => app.getAppPath());
  if (packaged) report.applicationSha256 = createHash('sha256').update(await readFile(applicationPath)).digest('hex');
  const page = await app.firstWindow(); page.on('pageerror', e => report.errors.push(String(e)));
  await page.waitForSelector('.dropzone');
  await page.evaluate(() => window.aio.preferences({ theme: 'light' }));
  await page.reload(); await page.waitForSelector('.dropzone');
  await page.getByRole('button', { name: 'Download links', exact: true }).click();
  assert.match(await page.locator('.local-status').textContent(), /Internet required/);
  await page.screenshot({ path: join(output, 'downloads-light.png') });
  assert.equal(await page.locator('#download-format').inputValue(), 'mp4');
  await page.locator('#download-kind').selectOption('Audio');
  assert.equal(await page.locator('#download-format').inputValue(), 'mp3');
  assert.equal(await page.locator('#download-quality-field').isVisible(), false);
  assert.equal(await page.locator('#download-format option').count(), 6); report.checks.push('Video/audio selectors and explicit extensions work');
  await assert.rejects(page.evaluate(() => window.aio.download({ url: 'file:///C:/Windows/win.ini', kind: 'Audio', format: 'mp3', quality: 'best' })), /HTTP|public/); report.checks.push('Download IPC rejects non-web URLs');
  const destination = join(profile, 'downloads');
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, destination);
  await page.locator('.destination').click();
  await page.locator('#media-link').fill('https://samplelib.com/lib/preview/mp4/sample-5s.mp4');
  await page.getByRole('button', { name: 'Download', exact: true }).click();
  await page.waitForSelector('.download-row.running', { timeout: 10000 });
  await page.locator('#media-link').fill('https://example.com/next-link');
  await page.locator('#media-link').focus();
  await page.waitForFunction(() => document.querySelector('.download-row.completed, .download-row.failed'), null, { timeout: 90000, polling: 100 });
  const job = (await page.evaluate(() => window.aio.state())).downloads[0]; assert.equal(job.status, 'completed', job.message);
  assert.ok((await readFile(job.outputPath)).length > 0); assert.equal(await page.locator('#media-link').inputValue(), 'https://example.com/next-link');
  assert.equal(await page.locator('#media-link').evaluate(el => document.activeElement === el), true); report.checks.push('Real native download → MP3; progress preserves form values and focus');
  await app.evaluate(({ shell }) => { shell.showItemInFolder = path => { globalThis.aioRevealed = path; }; });
  await page.getByRole('button', { name: /Show file/ }).click(); assert.equal(await app.evaluate(() => globalThis.aioRevealed), job.outputPath); report.checks.push('Output reveal uses verified completed path');
  await page.evaluate(() => window.aio.download({ url: 'https://example.com/aio-missing-media.mp4', kind: 'Video', format: 'mp4', quality: '720' }));
  await page.waitForSelector('.download-row.failed', { timeout: 60000 });
  await page.locator('.download-error summary').click();
  await page.evaluate(() => window.aio.download({ url: 'https://samplelib.com/lib/preview/mp4/sample-5s.mp4', kind: 'Video', format: 'mp4', quality: '480' }));
  await page.locator('.download-error summary').focus();
  await page.waitForFunction(() => document.querySelectorAll('.download-row.completed').length === 2, null, { timeout: 90000, polling: 100 });
  assert.equal(await page.locator('.download-error').getAttribute('open') !== null, true);
  assert.equal(await page.locator('.download-error summary').evaluate(el => document.activeElement === el), true);
  report.checks.push('Expanded failure details and summary focus survive another real download');
  await page.screenshot({ path: join(output, 'downloads-error.png') }); report.checks.push('Failed remote link has inline recoverable error');
  await page.getByRole('button', { name: 'Settings', exact: true }).click(); await page.getByRole('button', { name: 'Dark', exact: true }).click();
  await page.getByRole('button', { name: 'Download links', exact: true }).click();
  await page.screenshot({ path: join(output, 'downloads-dark.png') });
  const window = await app.browserWindow(page); await window.evaluate(w => w.setSize(820, 600));
  await page.screenshot({ path: join(output, 'downloads-small.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.ok(await page.locator('.destination').isVisible());
  await page.emulateMedia({ forcedColors: 'active', reducedMotion: 'reduce' }); await page.locator('#media-link').focus();
  await page.screenshot({ path: join(output, 'downloads-accessibility.png') }); report.checks.push('Minimum window, themes, high contrast and reduced motion captured');
  await page.getByRole('button', { name: 'Convert files', exact: true }).first().click(); assert.match(await page.locator('.local-status').textContent(), /Offline & local/); report.checks.push('Local conversion keeps offline status');
  assert.deepEqual(report.errors, []); report.checks.push('No renderer exceptions');
} finally {
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1, checkboxChecked: false }); }).catch(() => {});
  await app.close(); await mkdir('output/playwright', { recursive: true });
  await writeFile(`output/playwright/downloads-${packaged ? 'packaged-' : ''}checks.json`, JSON.stringify(report, null, 2)); await rm(profile, { recursive: true, force: true }).catch(() => {});
}
console.log(JSON.stringify(report, null, 2));
